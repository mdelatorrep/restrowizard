-- Generador de la línea base del esquema (B-04).
--
-- Reconstruye, desde el catálogo de producción, el DDL del esquema public y de
-- lo que la app necesita fuera de él (buckets y políticas de storage, trigger de
-- auth, publicación de realtime). No incluye datos.
--
-- Uso: crear la función en un proyecto Supabase, llamar a
--   select public._ops_schema_dump();
-- y borrarla después. Ver docs/operacion/base-reproducible.md.

CREATE OR REPLACE FUNCTION public._ops_schema_dump()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
DECLARE
  out text := '';
  r record;
  cols text;
BEGIN
  out := out || E'-- Línea base generada desde el catálogo de producción el ' || to_char(now() AT TIME ZONE 'America/Bogota', 'YYYY-MM-DD HH24:MI') || E' (hora de Bogotá).\n'
             || E'-- No editar a mano: regenerar con supabase/tools/schema_dump.sql.\n\n'
             || E'SET check_function_bodies = off;\nSET client_min_messages = warning;\n\n';

  -- Extensiones
  out := out || E'-- Extensiones\n'
    || E'CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;\n'
    || E'CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;\n'
    || E'CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;\n'
    || E'CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;\n'
    || E'CREATE EXTENSION IF NOT EXISTS pg_cron;\n\n';

  -- Enums
  out := out || E'-- Tipos enumerados\n';
  FOR r IN
    SELECT t.typname, string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) labels
    FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace JOIN pg_enum e ON e.enumtypid = t.oid
    WHERE n.nspname = 'public' AND t.typtype = 'e'
    GROUP BY t.typname ORDER BY t.typname
  LOOP
    out := out || format(E'CREATE TYPE public.%I AS ENUM (%s);\n', r.typname, r.labels);
  END LOOP;

  -- Tipos compuestos sueltos (no de tablas)
  FOR r IN
    SELECT t.typname, string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', ' ORDER BY a.attnum) attrs
    FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    JOIN pg_class c ON c.oid = t.typrelid AND c.relkind = 'c'
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    WHERE n.nspname = 'public' AND t.typtype = 'c'
    GROUP BY t.typname ORDER BY t.typname
  LOOP
    out := out || format(E'CREATE TYPE public.%I AS (%s);\n', r.typname, r.attrs);
  END LOOP;
  out := out || E'\n';

  -- Secuencias
  out := out || E'-- Secuencias\n';
  FOR r IN
    SELECT c.relname, s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, s.seqcycle, format_type(s.seqtypid, NULL) typ
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace JOIN pg_sequence s ON s.seqrelid = c.oid
    WHERE n.nspname = 'public' AND c.relkind = 'S'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i') -- identity: van con la tabla
    ORDER BY c.relname
  LOOP
    out := out || format(E'CREATE SEQUENCE public.%I AS %s INCREMENT %s MINVALUE %s MAXVALUE %s START %s CACHE %s%s;\n',
      r.relname, r.typ, r.seqincrement, r.seqmin, r.seqmax, r.seqstart, r.seqcache, CASE WHEN r.seqcycle THEN ' CYCLE' ELSE '' END);
  END LOOP;
  out := out || E'\n';

  -- Funciones (antes que las tablas: defaults y checks pueden usarlas)
  out := out || E'-- Funciones\n';
  FOR r IN
    SELECT p.oid FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind IN ('f','p')
      AND p.proname <> '_ops_schema_dump'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e') -- de extensiones
    ORDER BY p.proname, p.oid
  LOOP
    out := out || pg_get_functiondef(r.oid) || E';\n\n';
  END LOOP;

  -- Tablas
  out := out || E'-- Tablas\n';
  FOR r IN
    SELECT c.oid, c.relname, c.relkind, c.relpersistence
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'e')
    ORDER BY c.relname
  LOOP
    SELECT string_agg(
      format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
      || CASE
           WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
           WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
           WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
           WHEN ad.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
           ELSE '' END
      || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
      E',\n' ORDER BY a.attnum)
    INTO cols
    FROM pg_attribute a LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE a.attrelid = r.oid AND a.attnum > 0 AND NOT a.attisdropped;
    out := out || format(E'CREATE %sTABLE public.%I (\n%s\n);\n\n',
      CASE WHEN r.relpersistence = 'u' THEN 'UNLOGGED ' ELSE '' END, r.relname, coalesce(cols, ''));
  END LOOP;

  -- Propiedad de secuencias
  FOR r IN
    SELECT s.relname seq, t.relname tbl, a.attname col
    FROM pg_depend d
    JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S'
    JOIN pg_class t ON t.oid = d.refobjid
    JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
    JOIN pg_namespace n ON n.oid = s.relnamespace
    WHERE n.nspname = 'public' AND d.deptype = 'a'
    ORDER BY 1
  LOOP
    out := out || format(E'ALTER SEQUENCE public.%I OWNED BY public.%I.%I;\n', r.seq, r.tbl, r.col);
  END LOOP;
  out := out || E'\n';

  -- Restricciones: PK, únicas, checks y exclusión; luego llaves foráneas
  out := out || E'-- Restricciones\n';
  FOR r IN
    SELECT c.relname, k.conname, pg_get_constraintdef(k.oid) def, k.contype
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND k.contype IN ('p','u','c','x') AND c.relkind IN ('r','p')
    ORDER BY CASE k.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 ELSE 2 END, c.relname, k.conname
  LOOP
    out := out || format(E'ALTER TABLE public.%I ADD CONSTRAINT %I %s;\n', r.relname, r.conname, r.def);
  END LOOP;
  FOR r IN
    SELECT c.relname, k.conname, pg_get_constraintdef(k.oid) def
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND k.contype = 'f' AND c.relkind IN ('r','p')
    ORDER BY c.relname, k.conname
  LOOP
    out := out || format(E'ALTER TABLE public.%I ADD CONSTRAINT %I %s;\n', r.relname, r.conname, r.def);
  END LOOP;
  out := out || E'\n';

  -- Índices que no vienen de una restricción
  out := out || E'-- Índices\n';
  FOR r IN
    SELECT pg_get_indexdef(i.indexrelid) def
    FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid)
    ORDER BY 1
  LOOP
    out := out || r.def || E';\n';
  END LOOP;
  out := out || E'\n';

  -- Vistas, en orden de creación
  out := out || E'-- Vistas\n';
  FOR r IN
    SELECT c.relname, c.relkind, pg_get_viewdef(c.oid, true) def, c.reloptions
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('v','m')
    ORDER BY c.oid
  LOOP
    IF r.relkind = 'm' THEN
      out := out || format(E'CREATE MATERIALIZED VIEW public.%I AS\n%s\nWITH NO DATA;\n\n', r.relname, rtrim(r.def, ';'));
    ELSE
      out := out || format(E'CREATE VIEW public.%I%s AS\n%s\n\n', r.relname,
        CASE WHEN r.reloptions IS NOT NULL THEN ' WITH (' || array_to_string(r.reloptions, ', ') || ')' ELSE '' END, r.def);
    END IF;
  END LOOP;

  -- Triggers
  out := out || E'-- Triggers\n';
  FOR r IN
    SELECT pg_get_triggerdef(t.oid) def, t.tgenabled
    FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal
    ORDER BY c.relname, t.tgname
  LOOP
    out := out || r.def || E';\n';
  END LOOP;
  FOR r IN
    SELECT c.relname, t.tgname FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal AND t.tgenabled = 'D'
  LOOP
    out := out || format(E'ALTER TABLE public.%I DISABLE TRIGGER %I;\n', r.relname, r.tgname);
  END LOOP;
  out := out || E'\n';

  -- RLS y políticas
  out := out || E'-- Seguridad a nivel de fila\n';
  FOR r IN
    SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p') AND (c.relrowsecurity OR c.relforcerowsecurity)
    ORDER BY c.relname
  LOOP
    IF r.relrowsecurity THEN out := out || format(E'ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;\n', r.relname); END IF;
    IF r.relforcerowsecurity THEN out := out || format(E'ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;\n', r.relname); END IF;
  END LOOP;
  FOR r IN
    SELECT p.tablename, p.policyname, p.permissive, p.roles, p.cmd, p.qual, p.with_check
    FROM pg_policies p WHERE p.schemaname = 'public' ORDER BY p.tablename, p.policyname
  LOOP
    out := out || format(E'CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;\n',
      r.policyname, r.tablename, r.permissive, r.cmd,
      (SELECT string_agg(CASE WHEN x = 'public' THEN 'public' ELSE quote_ident(x) END, ', ') FROM unnest(r.roles) x),
      CASE WHEN r.qual IS NOT NULL THEN E'\n  USING (' || r.qual || ')' ELSE '' END,
      CASE WHEN r.with_check IS NOT NULL THEN E'\n  WITH CHECK (' || r.with_check || ')' ELSE '' END);
  END LOOP;
  out := out || E'\n';

  -- Permisos de tablas, vistas y secuencias
  out := out || E'-- Permisos\n';
  FOR r IN
    SELECT c.relname, c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p','v','m','S') ORDER BY c.relname
  LOOP
    out := out || format(E'REVOKE ALL ON %s public.%I FROM PUBLIC, anon, authenticated, service_role;\n',
      CASE WHEN r.relkind = 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, r.relname);
  END LOOP;
  FOR r IN
    SELECT c.relname, c.relkind, g.rolname grantee, string_agg(DISTINCT a.privilege_type, ', ') privs
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    CROSS JOIN LATERAL aclexplode(c.relacl) a
    JOIN pg_roles g ON g.oid = a.grantee
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p','v','m','S')
      AND g.rolname IN ('anon','authenticated','service_role')
    GROUP BY 1, 2, 3 ORDER BY 1, 3
  LOOP
    out := out || format(E'GRANT %s ON %s public.%I TO %I;\n', r.privs,
      CASE WHEN r.relkind = 'S' THEN 'SEQUENCE' ELSE 'TABLE' END, r.relname, r.grantee);
  END LOOP;

  -- Permisos de funciones
  FOR r IN
    SELECT p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args, p.proacl
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind IN ('f','p') AND p.proname <> '_ops_schema_dump'
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
    ORDER BY p.proname, p.oid
  LOOP
    IF r.proacl IS NOT NULL THEN
      out := out || format(E'REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated, service_role;\n', r.proname, r.args);
      out := out || coalesce((
        SELECT string_agg(format(E'GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;\n', r.proname, r.args,
                 CASE WHEN a.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(g.rolname) END), '')
        FROM aclexplode(r.proacl) a LEFT JOIN pg_roles g ON g.oid = a.grantee
        WHERE a.privilege_type = 'EXECUTE' AND (a.grantee = 0 OR g.rolname IN ('anon','authenticated','service_role'))
      ), '');
    END IF;
  END LOOP;
  out := out || E'\n';

  -- Trigger de auth.users (alta de perfil)
  out := out || E'-- Fuera de public: auth, storage y realtime\n';
  FOR r IN
    SELECT pg_get_triggerdef(t.oid) def FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'auth' AND c.relname = 'users' AND NOT t.tgisinternal
  LOOP
    out := out || r.def || E';\n';
  END LOOP;

  -- Buckets
  FOR r IN SELECT id, name, public, file_size_limit, allowed_mime_types FROM storage.buckets ORDER BY id LOOP
    out := out || format(E'INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;\n',
      r.id, r.name, r.public, coalesce(r.file_size_limit::text, 'NULL'),
      CASE WHEN r.allowed_mime_types IS NULL THEN 'NULL' ELSE quote_literal(r.allowed_mime_types::text) || '::text[]' END);
  END LOOP;
  FOR r IN
    SELECT p.policyname, p.permissive, p.roles, p.cmd, p.qual, p.with_check
    FROM pg_policies p WHERE p.schemaname = 'storage' AND p.tablename = 'objects' ORDER BY p.policyname
  LOOP
    out := out || format(E'CREATE POLICY %I ON storage.objects AS %s FOR %s TO %s%s%s;\n',
      r.policyname, r.permissive, r.cmd,
      (SELECT string_agg(CASE WHEN x = 'public' THEN 'public' ELSE quote_ident(x) END, ', ') FROM unnest(r.roles) x),
      CASE WHEN r.qual IS NOT NULL THEN E'\n  USING (' || r.qual || ')' ELSE '' END,
      CASE WHEN r.with_check IS NOT NULL THEN E'\n  WITH CHECK (' || r.with_check || ')' ELSE '' END);
  END LOOP;

  -- Publicación de realtime
  FOR r IN
    SELECT tablename FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public' ORDER BY 1
  LOOP
    out := out || format(E'ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;\n', r.tablename);
  END LOOP;

  RETURN out;
END
$fn$;

REVOKE ALL ON FUNCTION public._ops_schema_dump() FROM PUBLIC, anon, authenticated;
